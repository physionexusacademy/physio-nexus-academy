#!/usr/bin/env python3
"""
Builds the ethics pack: regenerates document 16 (submission checklist and the master list of every [TO COMPLETE] field) from the other documents, then converts
every document to Word (.docx) with pandoc and zips them.

    python3 docs/camera-form-check/tools/build-ethics-pack.py OUTPUT_DIR

Needs pandoc and python-docx. Edit the Markdown files, not the generated Word files, then run this again.
"""
import copy, glob, os, re, subprocess, sys, zipfile
from docx import Document
from docx.enum.section import WD_ORIENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.dirname(HERE)
OUT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(DOCS, "_build"))
LANDSCAPE = {"03", "07", "09", "10"}  # wide tables
VERSION = "0.1"
os.makedirs(OUT, exist_ok=True)


def number(path):
    return os.path.basename(path).split("-")[0]


def documents():
    return sorted(p for p in glob.glob(os.path.join(DOCS, "[0-9][0-9]-*.md")) if number(p) != "16")


def title_of(path):
    text = open(path, encoding="utf8").read()
    m = re.search(r'^title:\s*"(.*)"\s*$', text, re.M)
    return m.group(1) if m else os.path.basename(path)


# ---------- document 16: checklist and the master list of fields ----------
PLACEHOLDER = re.compile(r"\[TO COMPLETE[^\]]*\]")


def short(text, n):
    text = re.sub(r"[*`]", "", text)
    if len(text) <= n:
        return text
    return text[:n].rsplit(" ", 1)[0] + "…"


def placeholders(path):
    rows, heading = [], ""
    for line in open(path, encoding="utf8"):
        line = line.rstrip("\n")
        if line.startswith("#"):
            heading = line.lstrip("# ").strip()
        for m in PLACEHOLDER.finditer(line):
            before = re.sub(r"[*`>_|]", "", line[:m.start()])
            before = re.sub(r"\s+", " ", before).strip(" -:")
            if len(before) > 70:
                before = before[-70:]
                before = before[before.find(" ") + 1:] if " " in before else before
            rows.append((short(heading, 60), before, m.group(0).replace("|", "/")))
    return rows


def build_16():
    docs = documents()
    out = ['---', 'title: "Submission checklist and master list of every field to complete"',
           f'subtitle: "Camera exercise-feedback studies (PNA RehabVerse Form Check) — generated from documents 00 to 15, version {VERSION}"', '---', '']
    out += ["*Generated by `docs/camera-form-check/tools/build-ethics-pack.py`. Tick items off as you go. If you change a document, run the script again.*", ""]
    out += ["# 1. Submission checklist", "", "| Item | Needed by your committee? | Done | Attached |", "|---|---|---|---|"]
    for item in [
        "Signed application form of the ethics committee (its own form; use the summary table in document 04)",
        "Cover letter (document 04)", "Study protocol, Part A (document 01)", "Participant information sheet and consent form, English and Roman Urdu (document 02)",
        "Urdu-script version of the information sheet and consent form, if required", "Camera decisions annex (document 03)", "Data management plan (document 07)",
        "Statistical analysis plan (document 08)", "Risk management file (document 09)", "Forms and data collection sheets (document 10)",
        "Tool description and safety dossier (document 11)", "Declarations: investigator, interests, analyst, assessors (document 12)",
        "Site permission letter (document 12)", "Insurance or indemnity statement (document 12)", "Curricula vitae of the investigators",
        "Recruitment materials (document 14)", "Evidence of the registration plan (document 13)", "Part B protocol, for information (document 05)",
        "Optional module, only if you add it (document 15)", "Fee or receipt, if the committee charges one"]:
        out.append(f"| {item} | ☐ yes ☐ no | ☐ | ☐ |")
    out += ["", "# 2. Final check before you submit", ""]
    for i, item in enumerate([
        "Every `[TO COMPLETE]` below is filled or deliberately removed.",
        "The title, version number and date are the same on every document.",
        "The study codes, numbers of participants (8 to 10) and the eight movements are the same everywhere.",
        "The statement \"no video, image or landmark coordinates are stored\" is true for what you will actually run (or you have added the optional module and say so everywhere).",
        "Your commercial interest is stated in the protocol, the cover letter, the declaration and the consent forms.",
        "The Roman Urdu texts have been read by a fluent speaker; the Urdu-script version exists if required.",
        "The references have been checked against the originals.",
        "The jurisdiction-specific items (regulatory position, data protection, retention) are checked with your institution.",
        "Every signature and date is present.",
        "You have kept a copy of everything submitted."], 1):
        out.append(f"{i}. {item}")
    out += ["", "# 3. Every field you must complete, by document", ""]
    total = 0
    for path in docs:
        rows = placeholders(path) if number(path) != "00" else []
        if not rows:
            continue
        total += len(rows)
        out += [f"## Document {number(path)}: {short(title_of(path), 90)}", "", f"{len(rows)} field(s).", "", "| Section | Where | Field to complete |", "|---|---|---|"]
        out += [f"| {h or '(top)'} | {c} | {f} |" for h, c, f in rows]
        out.append("")
    out += [f"**Total: {total} fields in {len([d for d in docs if number(d) != '00' and placeholders(d)])} documents.**", ""]
    target = os.path.join(DOCS, "16-submission-checklist-and-placeholders.md")
    open(target, "w", encoding="utf8").write("\n".join(out))
    return target, total


# ---------- Word reference documents (portrait and landscape, with table borders) ----------
def reference(landscape):
    ref = os.path.join(OUT, f"_reference-{'landscape' if landscape else 'portrait'}.docx")
    subprocess.run(["pandoc", "-o", ref, "--print-default-data-file", "reference.docx"], check=True)
    doc = Document(ref)
    for section in doc.sections:
        if landscape:
            section.orientation = WD_ORIENT.LANDSCAPE
            section.page_width, section.page_height = Cm(29.7), Cm(21.0)
        else:
            section.page_width, section.page_height = Cm(21.0), Cm(29.7)
        section.left_margin = section.right_margin = Cm(1.8 if landscape else 2.0)
        section.top_margin = section.bottom_margin = Cm(1.8)
    for name in ("Normal", "Body Text", "First Paragraph", "Compact"):
        if name in [s.name for s in doc.styles]:
            doc.styles[name].font.name = "Calibri"
            doc.styles[name].font.size = Pt(10 if landscape else 10.5)
    styles = {s.name: s for s in doc.styles}
    table = styles.get("Table")
    if table is not None:
        tbl_pr = table.element.find(qn("w:tblPr"))
        if tbl_pr is None:
            tbl_pr = OxmlElement("w:tblPr")
            table.element.append(tbl_pr)
        borders = OxmlElement("w:tblBorders")
        for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
            el = OxmlElement(f"w:{edge}")
            el.set(qn("w:val"), "single"); el.set(qn("w:sz"), "4"); el.set(qn("w:space"), "0"); el.set(qn("w:color"), "999999")
            borders.append(el)
        for old in tbl_pr.findall(qn("w:tblBorders")):
            tbl_pr.remove(old)
        tbl_pr.append(borders)
    doc.save(ref)
    return ref



# ---------- table column widths: pandoc takes the relative widths of a pipe table from the dashes of its separator line ----------
def split_row(line):
    cells, cur, esc = [], "", False
    for ch in line.strip().strip("|"):
        if ch == "|" and not esc:
            cells.append(cur); cur = ""
        else:
            cur += ch
        esc = (ch == "\\")
    cells.append(cur)
    return [c.strip() for c in cells]


def weigh_tables(text):
    lines, out, i = text.split("\n"), [], 0
    while i < len(lines):
        if lines[i].lstrip().startswith("|") and i + 1 < len(lines) and re.match(r"^\s*\|[\s:\-|]+\|\s*$", lines[i + 1]):
            j = i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                j += 1
            header = split_row(lines[i])
            rows = [split_row(lines[k]) for k in range(i + 2, j)] or [header]
            n = len(header)
            widths = []
            for c in range(n):
                longest = max((len(r[c]) if c < len(r) else 0) for r in rows)
                typical = sorted(len(r[c]) if c < len(r) else 0 for r in rows)[len(rows) // 2]
                floor = max(8, 0.9 * len(header[c]) if len(header[c]) <= 14 else 0.6 * len(header[c]))
                widths.append(min(60, max(floor, 0.5 * longest + 0.5 * typical)))
            total = sum(widths)
            seps = ["-" * max(3, round(100 * w / total)) for w in widths]
            out.extend(lines[i:i + 1]); out.append("|" + "|".join(seps) + "|"); out.extend(lines[i + 2:j])
            i = j
        else:
            out.append(lines[i]); i += 1
    return "\n".join(out)


def main():
    target, total = build_16()
    print(f"document 16 regenerated: {total} fields to complete")
    refs = {False: reference(False), True: reference(True)}
    written = []
    for path in sorted(glob.glob(os.path.join(DOCS, "[0-9][0-9]-*.md"))):
        name = os.path.splitext(os.path.basename(path))[0]
        out = os.path.join(OUT, f"{name}.docx")
        src_dir = os.path.join(OUT, "_src"); os.makedirs(src_dir, exist_ok=True)
        src = os.path.join(src_dir, f"{name}.md")
        open(src, "w", encoding="utf8").write(weigh_tables(open(path, encoding="utf8").read()))
        subprocess.run(["pandoc", src, "-f", "markdown+pipe_tables+yaml_metadata_block", "-o", out, "--reference-doc", refs[number(path) in LANDSCAPE], "--columns=120"], check=True)
        written.append(out)
    zip_path = os.path.join(OUT, f"ethics-pack-v{VERSION}.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for out in written:
            z.write(out, os.path.basename(out))
    print(f"{len(written)} Word documents and {zip_path}")


main()
