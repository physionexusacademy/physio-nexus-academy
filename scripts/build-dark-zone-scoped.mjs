#!/usr/bin/env node
/**
 * Writes src/app/dark-zone.scoped.generated.css: the dark 3D zone (src/app/dark-zone.css and the two files it imports) with every rule
 * already limited to dark mode (`:where(html:not([data-theme="light"])) …`), so the light switch works whatever the build does with
 * PostCSS plugins. (The production build once shipped these rules without the prefix, and the site stayed dark in light mode.)
 * :where() keeps each rule's specificity exactly as written.
 *
 *   node scripts/build-dark-zone-scoped.mjs          write the file
 *   node scripts/build-dark-zone-scoped.mjs --check  fail if it is out of date or any rule is unscoped (CI)
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const DARK_ONLY = ':where(html:not([data-theme="light"]))';
const dir = path.resolve("src/app");
const entry = path.join(dir, "dark-zone.css");
const target = path.join(dir, "dark-zone.scoped.generated.css");

function inline(file) {
  const root = postcss.parse(fs.readFileSync(file, "utf8"), { from: file });
  root.walkAtRules("import", (rule) => {
    const name = rule.params.replace(/^url\(|\)$/g, "").replace(/["']/g, "").trim();
    const child = inline(path.resolve(path.dirname(file), name));
    rule.replaceWith(child.nodes);
  });
  return root;
}

const root = inline(entry);
root.walkComments((c) => c.remove());
root.walkRules((rule) => {
  if (rule.parent && rule.parent.type === "atrule" && /keyframes/i.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map((s) => (s.startsWith(DARK_ONLY) ? s : `${DARK_ONLY} ${s.trim()}`));
});
const css =
  "/* GENERATED by scripts/build-dark-zone-scoped.mjs from dark-zone.css (+ its imports): every rule applies in dark mode only. Do not edit by hand. */\n" +
  root.toString().replace(/\n{3,}/g, "\n\n").trim() +
  "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== css) {
    console.error("dark-zone.scoped.generated.css is out of date: run node scripts/build-dark-zone-scoped.mjs");
    process.exit(1);
  }
  let rules = 0;
  postcss.parse(css).walkRules((rule) => {
    if (rule.parent && rule.parent.type === "atrule" && /keyframes/i.test(rule.parent.name)) return;
    rules++;
    for (const s of rule.selectors) if (!s.startsWith(DARK_ONLY)) { console.error(`unscoped dark-zone rule: ${s}`); process.exit(1); }
  });
  console.log(`Dark zone: ${rules} rules, all limited to dark mode; file is fresh.`);
} else {
  fs.writeFileSync(target, css);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${(css.length / 1024).toFixed(1)} KB)`);
}
