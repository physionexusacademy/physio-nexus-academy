import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { techniqueDepthSlugs } from "../src/lib/manual-therapy-depth.ts";

/**
 * Builds the Daily Clinical Challenge's lesson-based question pool from the PNA Teacher lessons: every understanding check
 * (clinical reasoning and knowledge questions, each option explained) becomes a daily question whose "learn more" link is the
 * lesson it came from. Run after the lessons change:  node --experimental-strip-types scripts/build-daily-pool.ts
 * Answer positions are shuffled with a fixed seed so the right answer is not always in the same place.
 */
const lessonDir = new URL("../public/teacher-data/lessons/", import.meta.url);
const manual = new Set<string>(techniqueDepthSlugs());
const plain = (text: string) => text.replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
/** Questions that lean on something on the lesson screen (a widget, a case above, a slider) do not make sense on their own. */
const NEEDS_CONTEXT = /\b(above|earlier|previous|this lesson|the widget|you just|slider|drag|tap |click|as shown|shown here|the diagram|the chart|the graph)\b/i;

/** Generic stems that only make sense inside their lesson. */
const GENERIC = /^(imagine the patient|final check|was the builder|which statement is sound)/i;

function seeded(text: string) {
  let h = 2166136261;
  for (const ch of text) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return () => {
    h = (h + 0x6d2b79f5) | 0;
    let t = Math.imul(h ^ (h >>> 15), 1 | h);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

type Item = { id: string; topic: string; question: string; options: string[]; correct: number; explanation: string; href: string; linkTitle: string };
const seen = new Set<string>();
const pool: Item[] = [];

for (const file of readdirSync(lessonDir).sort()) {
  const lesson = JSON.parse(readFileSync(new URL(file, lessonDir), "utf8"));
  const href = (manual.has(lesson.slug) ? "/manual-therapy/" : "/learn/") + lesson.slug;
  let n = 0;
  for (const beat of lesson.beats) {
    if (beat.type !== "check") continue;
    n++;
    const question = plain(beat.question.en);
    const options = beat.options.map((option: any) => ({ text: plain(option.text.en), correct: Boolean(option.correct), feedback: plain(option.feedback.en) }));
    const right = options.filter((option: any) => option.correct);
    if (right.length !== 1 || options.length < 2 || options.length > 4) continue;
    if (question.length < 25 || question.length > 280 || NEEDS_CONTEXT.test(question) || GENERIC.test(question)) continue;
    if (options.some((option: any) => option.text.length < 1 || option.text.length > 170 || NEEDS_CONTEXT.test(option.text))) continue;
    if (right[0].feedback.length < 20 || seen.has(question.toLowerCase())) continue;
    seen.add(question.toLowerCase());
    const random = seeded(lesson.slug + n);
    const order = options.map((_: unknown, index: number) => index);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    const shuffled = order.map((index: number) => options[index]);
    pool.push({
      id: `lq-${lesson.slug}-${n}`.slice(0, 64),
      topic: String(lesson.area),
      question,
      options: shuffled.map((option: any) => option.text),
      correct: shuffled.findIndex((option: any) => option.correct),
      explanation: right[0].feedback,
      href,
      linkTitle: String(lesson.title),
    });
  }
}

const header = "/* Generated by scripts/build-daily-pool.ts from the PNA Teacher lessons. Do not edit by hand. */\n";
const type = "export type GeneratedDailyQuestion = { id: string; topic: string; question: string; options: string[]; correct: number; explanation: string; href: string; linkTitle: string };\n";
writeFileSync(new URL("../src/lib/daily-content/pool.generated.ts", import.meta.url), header + type + "export const generatedDailyPool: GeneratedDailyQuestion[] = " + JSON.stringify(pool) + ";\n");
const areas: Record<string, number> = {};
for (const item of pool) areas[item.topic] = (areas[item.topic] ?? 0) + 1;
console.log("daily pool:", pool.length, "questions from", Object.keys(areas).length, "areas;", pool.filter((q) => q.options.length === 3).length, "with three options");
